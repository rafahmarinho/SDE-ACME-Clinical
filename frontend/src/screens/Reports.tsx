import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { Download, FilePlus2 } from 'lucide-react'
import { type FormEvent, useState } from 'react'
import { useNavigate } from 'react-router'
import { EmptyState, ErrorState, Field, Skeleton } from '../components/ui'
import { useAuth } from '../hooks/useAuth'
import { useToast } from '../hooks/useToast'
import { bytes, fmtDateTime, REPORT_LABELS } from '../lib/format'
import { download, errorMessage } from '../services/api'
import { Api } from '../services/endpoints'

export default function Reports() {
  const { can } = useAuth()
  const navigate = useNavigate()
  const toast = useToast()
  const queryClient = useQueryClient()
  const reports = useQuery({ queryKey: ['reports'], queryFn: Api.reports })
  const patients = useQuery({
    queryKey: ['patients', 'report-picker'],
    queryFn: () => Api.searchPatients({ page_size: 100 }),
    enabled: can('patients:view'),
  })
  const kinds = reports.data?.kinds ?? []
  const [form, setForm] = useState({ kind: '', period_hours: 12, patient_id: '', deidentified: false })
  const kind = form.kind || kinds[0] || ''
  const create = useMutation({
    mutationFn: () =>
      Api.createReport({ kind, period_hours: form.period_hours, patient_id: kind === 'patient_vitals' ? form.patient_id || null : null, deidentified: form.deidentified }),
    onSuccess: (r) => {
      toast(`${r.title} generated (${r.row_count} rows).`, 'success')
      void queryClient.invalidateQueries({ queryKey: ['reports'] })
      navigate(`/reports/${r.id}`)
    },
    onError: (err) => toast(errorMessage(err), 'error'),
  })
  const submit = (e: FormEvent) => {
    e.preventDefault()
    create.mutate()
  }

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Reports</h1>
          <p>Generated by the ACME Clinical service and stored privately. Downloads are verified against their SHA-256 fingerprint.</p>
        </div>
      </div>
      <div className="split">
        <div className="card">
          <div className="card-head">
            <h2>Generated reports</h2>
          </div>
          {reports.error && (
            <div className="card-body">
              <ErrorState error={reports.error} onRetry={() => void reports.refetch()} />
            </div>
          )}
          {reports.isLoading && (
            <div className="card-body">
              <Skeleton height={160} />
            </div>
          )}
          {reports.data?.items.length === 0 && <EmptyState title="No reports yet">Generate your first report with the form.</EmptyState>}
          {reports.data && reports.data.items.length > 0 && (
            <div className="table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th>Report</th>
                    <th>Created</th>
                    <th className="num">Rows</th>
                    <th />
                  </tr>
                </thead>
                <tbody>
                  {reports.data.items.map((r) => (
                    <tr key={r.id} className="clickable" onClick={() => navigate(`/reports/${r.id}`)}>
                      <td>
                        <strong>{r.title}</strong>
                        <div className="muted small">
                          {r.params.period_hours ? `Last ${r.params.period_hours} h · ` : ''}
                          {bytes(r.size_bytes)}
                          {r.deidentified && ' · de-identified'}
                        </div>
                      </td>
                      <td className="small">
                        {fmtDateTime(r.created_at)}
                        <div className="muted">{r.created_by_name}</div>
                      </td>
                      <td className="num">{r.row_count}</td>
                      <td>
                        <button
                          className="btn btn-sm"
                          onClick={(e) => {
                            e.stopPropagation()
                            download(`/reports/${r.id}/download`, 'report.csv').catch((err) => toast(errorMessage(err), 'error'))
                          }}
                        >
                          <Download size={14} /> CSV
                        </button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
        <form className="card card-pad stack" onSubmit={submit}>
          <h2>New report</h2>
          <Field label="Report type" htmlFor="kind">
            <select id="kind" className="select" value={kind} onChange={(e) => setForm({ ...form, kind: e.target.value })}>
              {kinds.map((k) => (
                <option key={k} value={k}>
                  {REPORT_LABELS[k]}
                </option>
              ))}
            </select>
          </Field>
          {kind !== 'device_maintenance' && (
            <Field label="Period" htmlFor="period">
              <select id="period" className="select" value={form.period_hours} onChange={(e) => setForm({ ...form, period_hours: Number(e.target.value) })}>
                <option value={1}>Last hour</option>
                <option value={4}>Last 4 hours</option>
                <option value={12}>Last 12 hours (shift)</option>
                <option value={24}>Last 24 hours</option>
                <option value={168}>Last 7 days</option>
              </select>
            </Field>
          )}
          {kind === 'patient_vitals' && (
            <Field label="Patient" htmlFor="patient">
              <select id="patient" className="select" value={form.patient_id} onChange={(e) => setForm({ ...form, patient_id: e.target.value })} required>
                <option value="">Choose a patient…</option>
                {patients.data?.items.map((p) => (
                  <option key={p.id} value={p.id}>
                    {p.bed_id} · {p.last_name}, {p.first_name}
                  </option>
                ))}
              </select>
            </Field>
          )}
          {kind !== 'device_maintenance' && (
            <label className="checkbox">
              <input type="checkbox" checked={form.deidentified} onChange={(e) => setForm({ ...form, deidentified: e.target.checked })} />
              De-identify (for quality review or research — names replaced by pseudonyms, restricted patients excluded)
            </label>
          )}
          <button className="btn btn-primary" disabled={!kind || create.isPending || (kind === 'patient_vitals' && !form.patient_id)}>
            <FilePlus2 size={16} /> {create.isPending ? 'Generating…' : 'Generate report'}
          </button>
        </form>
      </div>
    </>
  )
}
